-- Context Setup
USE ROLE ACCOUNTADMIN;
CREATE OR REPLACE DATABASE TASK_DEMO_DB;
CREATE OR REPLACE SCHEMA TASK_DEMO_DB.PUBLIC;
USE SCHEMA TASK_DEMO_DB.PUBLIC;

-- Warehouse Setup
CREATE OR REPLACE WAREHOUSE TASK_WH 
    WITH WAREHOUSE_SIZE = 'XSMALL' 
    AUTO_SUSPEND = 60 
    AUTO_RESUME = TRUE;

-- Sample Target Tables
CREATE OR REPLACE TABLE RAW_LOGS (
    LOG_ID INT AUTOINCREMENT,
    LOG_MESSAGE STRING,
    CREATED_AT TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP()
);

CREATE OR REPLACE TABLE SUMMARY_METRICS (
    METRIC_DATE DATE,
    TOTAL_LOGS INT,
    PROCESSED_AT TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP()
);

-- Required Grant for Task Execution (Required if using non-ACCOUNTADMIN roles)
GRANT EXECUTE TASK ON ACCOUNT TO ROLE SYSADMIN;


-- Option 1: Using Schedule Interval (e.g., Every 1 Minute)
CREATE OR REPLACE TASK INSERT_LOG_TASK
    WAREHOUSE = TASK_WH
    SCHEDULE = '1 MINUTE'
AS
    INSERT INTO RAW_LOGS (LOG_MESSAGE) 
    VALUES ('Automated Log Entry generated by Snowflake Task');

-- Option 2: Using CRON Schedule (e.g., Every day at Midnight UTC)
CREATE OR REPLACE TASK DAILY_LOG_CLEANUP_TASK
    WAREHOUSE = TASK_WH
    SCHEDULE = 'USING CRON 0 0 * * * UTC'
AS
    DELETE FROM RAW_LOGS 
    WHERE CREATED_AT < DATEADD(DAY, -30, CURRENT_TIMESTAMP());



-- Serverless tasks use Snowflake-managed compute resources
CREATE OR REPLACE TASK SERVERLESS_INSERT_TASK
    SCHEDULE = '5 MINUTE'
    USER_TASK_MANAGED_INITIAL_WAREHOUSE_SIZE = 'XSMALL'
AS
    INSERT INTO RAW_LOGS (LOG_MESSAGE) 
    VALUES ('Serverless task execution');



-- Step 1: Root Task (Parent Task with Schedule)
CREATE OR REPLACE TASK ROOT_TASK_INGEST
    WAREHOUSE = TASK_WH
    SCHEDULE = '5 MINUTE'
AS
    INSERT INTO RAW_LOGS (LOG_MESSAGE) 
    VALUES ('Root task batch execution');

-- Step 2: Child Task 1 (Executes AFTER Root Task completes)
CREATE OR REPLACE TASK CHILD_TASK_SUMMARIZE
    WAREHOUSE = TASK_WH
    AFTER ROOT_TASK_INGEST
AS
    INSERT INTO SUMMARY_METRICS (METRIC_DATE, TOTAL_LOGS)
    SELECT 
        CURRENT_DATE(), 
        COUNT(*) 
    FROM RAW_LOGS 
    WHERE CAST(CREATED_AT AS DATE) = CURRENT_DATE();

-- Step 3: Child Task 2 (Executes AFTER Child Task 1 completes)
CREATE OR REPLACE TASK CHILD_TASK_CLEANUP
    WAREHOUSE = TASK_WH
    AFTER CHILD_TASK_SUMMARIZE
AS
    OPTIMIZE TABLE RAW_LOGS; -- Or any downstream action/stored procedure call



-- Resume Tasks (Must resume Child tasks BEFORE Parent tasks)
ALTER TASK CHILD_TASK_CLEANUP RESUME;
ALTER TASK CHILD_TASK_SUMMARIZE RESUME;
ALTER TASK ROOT_TASK_INGEST RESUME;

-- Suspend Tasks (Always suspend Parent task FIRST)
ALTER TASK ROOT_TASK_INGEST SUSPEND;
ALTER TASK CHILD_TASK_SUMMARIZE SUSPEND;
ALTER TASK CHILD_TASK_CLEANUP SUSPEND;

-- Manually Trigger a Root Task (For testing without waiting on schedule)
EXECUTE TASK ROOT_TASK_INGEST;

-- Modify Task Properties
ALTER TASK INSERT_LOG_TASK SET SCHEDULE = '10 MINUTE';
ALTER TASK INSERT_LOG_TASK SET WAREHOUSE = 'SMALL';


-- 1. List all tasks in current context
SHOW TASKS;

-- 2. Check execution history (Past runs, status, error codes)
SELECT 
    NAME,
    STATE,
    SCHEDULED_TIME,
    COMPLETED_TIME,
    ERROR_CODE,
    ERROR_MESSAGE
FROM TABLE(INFORMATION_SCHEMA.TASK_HISTORY(
    RESULT_LIMIT => 100,
    SCHEDULED_TIME_RANGE_START => DATEADD('HOUR', -24, CURRENT_TIMESTAMP())
))
ORDER BY SCHEDULED_TIME DESC;

-- 3. Check Task DAG Dependencies & Graph relationships
SELECT * 
FROM TABLE(INFORMATION_SCHEMA.TASK_DEPENDENTS(
    TASK_NAME => 'ROOT_TASK_INGEST', 
    RECURSIVE => TRUE
));
