SELECT * FROM SECURITY_LAB_DB.STD_SCH.RAM_TABLE;

GRANT SELECT ON TABLE SECURITY_LAB_DB.STD_SCH.RAM_TABLE TO ROLE SHAM;

USE ROLE SHAM;
SELECT * FROM SECURITY_LAB_DB.STD_SCH.RAM_TABLE;

