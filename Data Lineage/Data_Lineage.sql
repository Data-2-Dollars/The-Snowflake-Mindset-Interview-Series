-- 1. Create a dedicated sandbox environment
CREATE OR REPLACE DATABASE LINEAGE_DEMO_DB;
CREATE OR REPLACE SCHEMA LINEAGE_DEMO_SCHEMA;
USE SCHEMA LINEAGE_DEMO_DB.LINEAGE_DEMO_SCHEMA;

-- 2. Create Base Raw Table
CREATE OR REPLACE TABLE RAW_CUSTOMERS (
    CUSTOMER_ID INT,
    FIRST_NAME VARCHAR,
    LAST_NAME VARCHAR,
    EMAIL VARCHAR,
    CREDIT_CARD VARCHAR
);

-- Insert sample records
INSERT INTO RAW_CUSTOMERS VALUES 
