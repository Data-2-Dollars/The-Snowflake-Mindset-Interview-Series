-- 3. Data Movement: Create Processed Table (CTAS)
CREATE OR REPLACE TABLE PROCESSED_CUSTOMERS AS
SELECT 
    CUSTOMER_ID,
    UPPER(CONCAT(FIRST_NAME, ' ', LAST_NAME)) AS FULL_NAME,
    EMAIL
FROM RAW_CUSTOMERS;

-- 4. Object Dependency: Create downstream Analytics View
CREATE OR REPLACE VIEW VW_ACTIVE_CUSTOMERS AS
SELECT 
    CUSTOMER_ID, 
    FULL_NAME 
FROM PROCESSED_CUSTOMERS;
